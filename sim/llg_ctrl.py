"""Control experiment for the rotation scan (report5 sec. 6): separate the lattice-lattice interaction from the
box-approximant detuning.  For each (delta, H) the two-lattice state 'both' is projected in Fourier space onto the
reciprocal sublattice generated by the q- hexagon (v1, v2) and onto the one generated by its q+ hexagon (u1, u2);
each projection is normalised (|m| = 1) and relaxed alone (a single-lattice field stays in its sublattice by
translation symmetry).  E_int(theta) = dE_both - dE_minus - dE_plus(theta), all dE = E - E_sat (E_sat = -2H).
usage: python llg_ctrl.py WORKER NWORKERS        (resume-safe: finished jobs are skipped)"""
import json, os, sys, time, fcntl
import numpy as np
sys.path.insert(0, os.path.dirname(__file__))
import llg, llg_run as lr
from llg_m import A, D1, RHO, J, HS, QM, QP, BX, BY, LX, LY, RUNS, qm_lattice

DELTAS = ['-20', '-10', '-5', '+0', '+5', '+10', '+20']
HF = [0.3, 0.372, 0.4185, 0.4418]
OUT = os.path.join(RUNS, 'llg_ctrl.json')


def field_path(d, hf):
    if hf == 0.3: return os.path.join(RUNS, 'fields', f'llgM_M1_d{d}_m.npy')
    return os.path.join(RUNS, 'fields', f'llgM_cont_M1_d{d}_h{hf}_m.npy')


def plus_generators(m):
    pk = lr.find_peaks_llg(m, BX, BY, rel=1e-4)
    cand = [p for p in pk if abs(p['k'] / QP - 1) < 0.08]
    cand.sort(key=lambda p: -p['a'])
    if not cand: return None
    g1 = np.array(cand[0]['n'])
    for p in cand[1:]:
        g2 = np.array(p['n'])
        if abs(g1[0] * g2[1] - g1[1] * g2[0]) > 0:
            return [tuple(int(x) for x in g1), tuple(int(x) for x in g2)], [cand[0]['a'], p['a']]
    return None


def sublattice_mask(g1, g2):
    nx = np.fft.fftfreq(LX, 1.0 / LX).astype(int); ny = np.fft.fftfreq(LY, 1.0 / LY).astype(int)
    NX, NY = np.meshgrid(nx, ny, indexing='ij')
    det = g1[0] * g2[1] - g1[1] * g2[0]
    an = NX * g2[1] - NY * g2[0]; bn = g1[0] * NY - g1[1] * NX          # a*det, b*det
    return (an % det == 0) & (bn % det == 0)


def project(m, mask):
    mh = np.fft.fft2(m, axes=(1, 2)); return np.real(np.fft.ifft2(mh * mask[None], axes=(1, 2)))


def relax(m0, H, nmax=15000, chunk=2500):
    sim = llg.LLG(A, D1, RHO * D1, J / 2, H, 0.0, L=(LX, LY), B=(BX, BY)); sim.set_m(m0)
    Es = [sim.energy()]
    for c in range(nmax // chunk):
        sim.step(chunk); Es.append(sim.energy())
        if abs(Es[-1] - Es[-2]) < 1e-11 and sim.residual() < 1e-7: break
    return sim, dict(E=Es[-1], dE_sat=Es[-1] + 2 * H, dE_last_chunk=Es[-1] - Es[-2], res=sim.residual(), steps=(len(Es) - 1) * chunk, mz=sim.mz_mean())


def load_out():
    return json.load(open(OUT)) if os.path.exists(OUT) else {}


def save_entry(key, val):
    with open(OUT + '.lock', 'w') as lk:
        fcntl.flock(lk, fcntl.LOCK_EX)
        d = load_out(); d[key] = val; json.dump(d, open(OUT, 'w'), indent=1, default=float)
        fcntl.flock(lk, fcntl.LOCK_UN)


def jobs():
    js = []
    for hf in HF:
        js.append(('minus', '-5', hf)); js.append(('minus', '+5', hf))          # q- alone (two sources: consistency check)
        for d in DELTAS:
            js.append(('plus', d, hf))
            if hf != 0.3: js.append(('both', d, hf))                              # continue the two-lattice state to convergence
    return js


if __name__ == '__main__':
    if sys.argv[1] == 'idx':
        sel = set(int(x) for x in sys.argv[2].split(','))
        w, nw = 0, 1
    else:
        sel = None; w, nw = int(sys.argv[1]), int(sys.argv[2])
    for i, (kind, d, hf) in enumerate(jobs()):
        if sel is not None:
            if i not in sel: continue
        elif i % nw != w: continue
        key = f'{kind}|{d}|{hf}'
        if key in load_out(): continue
        t0 = time.time(); H = hf * HS
        m = np.load(field_path(d, hf)).astype(float)
        info = {}
        if kind == 'both':
            m0 = m
        elif kind == 'minus':
            v = qm_lattice(); info['gen'] = [v[0], v[1]]
            m0 = project(m, sublattice_mask(v[0], v[1]))
        else:
            g = plus_generators(m)
            if g is None:
                save_entry(key, dict(error='no q+ peaks')); print(key, 'no q+ peaks', flush=True); continue
            info['gen'], info['gen_amp'] = g
            info['angle_u1_deg'] = float(np.degrees(np.arctan2(2 * np.pi * g[0][0][1] / BY, 2 * np.pi * g[0][0][0] / BX)) % 180)
            info['len_u_over_qp'] = [float(np.hypot(2 * np.pi * u[0] / BX, 2 * np.pi * u[1] / BY) / QP) for u in g[0]]
            m0 = project(m, sublattice_mask(*g[0]))
        sim, r = relax(m0, H)
        pk = lr.find_peaks_llg(sim.state(), BX, BY)
        r.update(info, kind=kind, delta=d, hfrac=hf, wall=time.time() - t0,
                 top=[(list(p['n']), round(p['k'] / QM, 3), round(p['angle'], 1), round(p['a'], 4)) for p in pk[:6]])
        save_entry(key, r)
        print(f"{key}: dE_sat={r['dE_sat']:.6e} last-chunk dE={r['dE_last_chunk']:.1e} res={r['res']:.1e} steps={r['steps']} {r['wall']:.0f}s", flush=True)
